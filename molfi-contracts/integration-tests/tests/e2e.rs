#[test]
fn confidential_withdraw_with_real_proof() {
    // The full privacy-pool exit, end to end, gated by a REAL Groth16
    // membership + nullifier proof verified on-chain by the real verifier:
    // deposit collateral -> operator checkpoints the Merkle root -> a private
    // withdrawal unlocks funds against a genuine proof -> nullifier burned.
    use withdraw_fixture as f;
    let env = Env::default();
    env.mock_all_auths();

    let admin = Address::generate(&env);
    let sac = env.register_stellar_asset_contract_v2(admin.clone());
    let token_addr = sac.address();
    let mint = StellarAssetClient::new(&env, &token_addr);
    let tok = TokenClient::new(&env, &token_addr);

    // REAL verifier loaded with the withdraw circuit's verifying key.
    let mut ic = Vec::new(&env);
    for e in f::VK_IC.iter() {
        ic.push_back(BytesN::from_array(&env, e));
    }
    let vk = molfi_verifier::VerifyingKey {
        alpha_g1: BytesN::from_array(&env, &f::VK_ALPHA),
        beta_g2: BytesN::from_array(&env, &f::VK_BETA),
        gamma_g2: BytesN::from_array(&env, &f::VK_GAMMA),
        delta_g2: BytesN::from_array(&env, &f::VK_DELTA),
        ic,
    };
    let verifier = env.register(molfi_verifier::Verifier, (admin.clone(), vk));

    let pool = env.register(PrivacyPool, (admin.clone(), verifier, token_addr.clone()));
    let pool_c = PrivacyPoolClient::new(&env, &pool);

    // A deposit funds the pool with collateral.
    let depositor = Address::generate(&env);
    mint.mint(&depositor, &100_000_000);
    pool_c.deposit(&depositor, &BytesN::from_array(&env, &[5u8; 32]), &100_000_000);
    assert_eq!(tok.balance(&pool), 100_000_000);

    // Operator checkpoints the circuit's (off-chain) Merkle root.
    let root = BytesN::from_array(&env, &f::PUBLIC[0]);
    pool_c.register_root(&root);

    // The real proof + its public signals [root, nullifierHash, recipient, amount].
    let proof = molfi_privacy_pool::Proof {
        a: BytesN::from_array(&env, &f::PROOF_A),
        b: BytesN::from_array(&env, &f::PROOF_B),
        c: BytesN::from_array(&env, &f::PROOF_C),
    };
    let mut sigs = Vec::new(&env);
    for s in f::PUBLIC.iter() {
        sigs.push_back(BytesN::from_array(&env, s));
    }

    // Withdraw to a fresh address — unlocked ONLY by the genuine proof.
    let recipient = Address::generate(&env);

    // Amount binding: paying a different amount than the proof authorizes fails.
    assert!(
        pool_c.try_withdraw(&proof, &sigs, &recipient, &50_000_000).is_err(),
        "amount not matching the proof must be rejected"
    );

    pool_c.withdraw(&proof, &sigs, &recipient, &100_000_000);
    assert_eq!(tok.balance(&recipient), 100_000_000, "real ZK proof unlocked the withdrawal");

    let nullifier = BytesN::from_array(&env, &f::PUBLIC[1]);
    assert!(pool_c.is_nullifier_used(&nullifier), "nullifier burned");

    // Same nullifier can't be spent twice.
    assert!(
        pool_c.try_withdraw(&proof, &sigs, &recipient, &100_000_000).is_err(),
        "double-spend rejected"
    );
}
